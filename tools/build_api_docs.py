"""Generate the mdBook API chapter from documented public Python callables."""

import importlib
import inspect
from pathlib import Path


def main() -> None:
    """Write signatures and docstrings without invoking any utility functions."""
    sections = ['# API reference\n\nGenerated by `tools/build_api_docs.py`.\n']
    for name in ('fileutils', 'utils', 'textutils', 'cprint', 'jobutils'):
        module = importlib.import_module(f'dh.{name}')
        sections.append(f'\n## dh.{name}\n')
        for symbol, obj in inspect.getmembers(module, inspect.isfunction):
            if symbol.startswith('_') or obj.__module__ != module.__name__:
                continue
            sections.append(f'\n### {symbol}\n\n```python\n{symbol}{inspect.signature(obj)}\n```\n\n'
                            f'{inspect.getdoc(obj) or "See the module source for implementation details."}\n')
    target = Path(__file__).resolve().parents[1] / 'docs/src/api.md'
    target.write_text(''.join(sections), encoding='utf-8')


if __name__ == '__main__':
    main()
